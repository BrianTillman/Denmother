// SyncResult holds the results of a sync operation
type SyncResult struct {
	EntitiesCount  int
	DevicesCount   int
	AreasCount     int
	EntityListPath string
	DeviceListPath string
	AreaListPath   string
	Entities       map[string]bool // Entity IDs for mismatch analysis
	Warnings       []string
}

// Syncer handles syncing entities from Home Assistant
type Syncer struct {
	client     *Client
	configPath string
	quiet      bool
}

// NewSyncer creates a new Syncer
func NewSyncer(haURL, haToken, configPath string) *Syncer {
	return &Syncer{
		client:     NewClient(haURL, haToken),
		configPath: configPath,
	}
}

// SetQuiet enables/disables quiet mode
func (s *Syncer) SetQuiet(quiet bool) {
	s.quiet = quiet
}

// SyncAll syncs entities, devices, and areas from Home Assistant
func (s *Syncer) SyncAll() (*SyncResult, error) {
	result := &SyncResult{}

	settings, err := project.ForConfig(s.configPath)
	if err != nil {
		return nil, err
	}
	refDir := settings.ReferencesDir
	if err := os.MkdirAll(refDir, 0755); err != nil {
		return nil, fmt.Errorf("failed to create reference directory: %w", err)
	}

	if !s.quiet {
		color.Cyan("Checking Home Assistant connectivity...")
	}
	if err := s.client.Ping(); err != nil {
		return nil, fmt.Errorf("cannot connect to Home Assistant: %w", err)
	}
	if !s.quiet {
		color.Green("  Connected to Home Assistant")
	}

	if !s.quiet {
		color.Cyan("\nFetching entities...")
	}
	entities, err := s.client.FetchEntities()
	if err != nil {
		return nil, err
	}
	result.EntitiesCount = len(entities)
	if !s.quiet {
		color.Green("  Fetched %d entities", len(entities))
	}

	result.Entities = make(map[string]bool, len(entities))
	for _, e := range entities {
		result.Entities[e.EntityID] = true
	}

	entityListPath := filepath.Join(refDir, "entity-list.txt")
	if err := s.saveEntityList(entities, entityListPath); err != nil {
		return nil, err
	}
	result.EntityListPath = entityListPath

	if !s.quiet {
		color.Cyan("\nFetching devices and areas...")
	}
	devices, areas, err := s.client.FetchDevicesAndAreas()
	if err != nil {
		result.Warnings = append(result.Warnings, fmt.Sprintf("device/area fetch was partial: %v", err))
		if !s.quiet {
			color.Yellow("  Warning: %v", err)
		}
	}

	// A non-nil slice is a successful fetch, including an empty registry.
	if devices != nil {
		result.DevicesCount = len(devices)
		if !s.quiet {
			color.Green("  Fetched %d devices", len(devices))
		}

		deviceListPath := filepath.Join(refDir, "device-list.txt")
		if err := s.saveDeviceList(devices, deviceListPath); err != nil {
			return nil, err
		}
		result.DeviceListPath = deviceListPath
	}

	// Failed datasets remain nil and retain their previous snapshot with a warning.
	if areas != nil {
		result.AreasCount = len(areas)
		if !s.quiet {
			color.Green("  Fetched %d areas", len(areas))
		}

		areaListPath := filepath.Join(refDir, "area-list.txt")
		if err := s.saveAreaList(areas, areaListPath); err != nil {
			return nil, err
		}
		result.AreaListPath = areaListPath
	}

	return result, nil
}

// SyncEntities syncs only entities from Home Assistant
func (s *Syncer) SyncEntities() (int, string, error) {
	settings, err := project.ForConfig(s.configPath)
	if err != nil {
		return 0, "", err
	}
	refDir := settings.ReferencesDir
	if err := os.MkdirAll(refDir, 0755); err != nil {
		return 0, "", fmt.Errorf("failed to create reference directory: %w", err)
	}

	entities, err := s.client.FetchEntities()
	if err != nil {
		return 0, "", err
	}

	entityListPath := filepath.Join(refDir, "entity-list.txt")
	if err := s.saveEntityList(entities, entityListPath); err != nil {
		return 0, "", err
	}

	return len(entities), entityListPath, nil
}

func (s *Syncer) saveEntityList(entities []EntityState, path string) error {
	entityIDs := make([]string, 0, len(entities))
	for _, e := range entities {
		entityIDs = append(entityIDs, e.EntityID)
	}
	sort.Strings(entityIDs)

	var buffer bytes.Buffer
	writer := bufio.NewWriter(&buffer)
	fmt.Fprintf(writer, "# Current Home Assistant Entities\n")
	fmt.Fprintf(writer, "# Generated: %s\n", time.Now().Format(time.RFC3339))
	fmt.Fprintf(writer, "# Total entities: %d\n", len(entityIDs))
	fmt.Fprintf(writer, "# This file was automatically generated by dm sync\n")
	fmt.Fprintln(writer)

	for _, id := range entityIDs {
		fmt.Fprintln(writer, id)
	}

	if err := writer.Flush(); err != nil {
		return fmt.Errorf("failed to write entity list: %w", err)
	}
	if err := util.WriteFileAtomic(path, buffer.Bytes(), 0644); err != nil {
		return fmt.Errorf("failed to publish entity list: %w", err)
	}

	if !s.quiet {
		color.Green("  Saved entity list to: %s", path)
	}
	return nil
}

func (s *Syncer) saveDeviceList(devices []Device, path string) error {
	sort.Slice(devices, func(i, j int) bool {
		return devices[i].Name < devices[j].Name
	})

	var buffer bytes.Buffer
	writer := bufio.NewWriter(&buffer)
	fmt.Fprintf(writer, "# Live Devices from Home Assistant API\n")
	fmt.Fprintf(writer, "# Generated: %s\n", time.Now().Format(time.RFC3339))
	fmt.Fprintf(writer, "# Total devices: %d\n", len(devices))
	fmt.Fprintln(writer)

	for _, d := range devices {
		identifier := ""
		if len(d.Identifiers) > 0 && len(d.Identifiers[0]) > 1 {
			identifier = d.Identifiers[0][1]
		}
		fmt.Fprintf(writer, "%s: %s (%s)\n", d.ID, d.Name, identifier)
	}

	if err := writer.Flush(); err != nil {
		return fmt.Errorf("failed to write device list: %w", err)
	}
	if err := util.WriteFileAtomic(path, buffer.Bytes(), 0644); err != nil {
		return fmt.Errorf("failed to publish device list: %w", err)
	}

	if !s.quiet {
		color.Green("  Saved device list to: %s", path)
	}
	return nil
}

