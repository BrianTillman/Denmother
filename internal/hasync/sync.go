// LoadEntityList loads entities from the entity-list.txt file
func LoadEntityList(configPath string) (map[string]bool, error) {
	settings, err := project.ForConfig(configPath)
	if err != nil {
		return nil, err
	}
	path := filepath.Join(settings.ReferencesDir, "entity-list.txt")
	file, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer file.Close()

	entities := make(map[string]bool)
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		entities[line] = true
	}

	return entities, scanner.Err()
}

// OrphanedDevice represents a device with no associated entities
type OrphanedDevice struct {
	Device       Device
	EntityCount  int
	HasEmptyName bool
}

// OrphanResult holds the results of orphan detection
type OrphanResult struct {
	TotalDevices    int
	OrphanedDevices []OrphanedDevice
	ReportPath      string
}

// FindOrphanedDevices identifies devices that have no associated entities
func (s *Syncer) FindOrphanedDevices() (*OrphanResult, error) {
	if !s.quiet {
		color.Cyan("\nAnalyzing devices for orphans...")
	}

	wsClient := NewWSClient(s.client.baseURL, s.client.token)
	if err := wsClient.Connect(); err != nil {
		return nil, fmt.Errorf("failed to connect WebSocket: %w", err)
	}
	defer wsClient.Close()

	devices, err := wsClient.FetchDevicesWS()
	if err != nil {
		return nil, fmt.Errorf("failed to fetch devices: %w", err)
	}
	if !s.quiet {
		color.Green("  Fetched %d devices", len(devices))
	}

	entityRegistry, err := wsClient.FetchEntityRegistryWS()
	if err != nil {
		return nil, fmt.Errorf("failed to fetch entity registry: %w", err)
	}
	if !s.quiet {
		color.Green("  Fetched %d entity registry entries", len(entityRegistry))
	}

	deviceEntityCount := make(map[string]int)
	for _, entry := range entityRegistry {
		if entry.DeviceID != "" {
			deviceEntityCount[entry.DeviceID]++
		}
	}

	var orphaned []OrphanedDevice
	for _, device := range devices {
		count := deviceEntityCount[device.ID]
		if count == 0 {
			orphaned = append(orphaned, OrphanedDevice{
				Device:       device,
				EntityCount:  0,
				HasEmptyName: strings.TrimSpace(device.Name) == "",
			})
		}
	}

	if !s.quiet {
		color.Yellow("  Found %d orphaned devices (no entities)", len(orphaned))
	}

	sort.Slice(orphaned, func(i, j int) bool {
		if orphaned[i].HasEmptyName != orphaned[j].HasEmptyName {
			return orphaned[i].HasEmptyName
		}
		return orphaned[i].Device.Name < orphaned[j].Device.Name
	})

	settings, err := project.ForConfig(s.configPath)
	if err != nil {
		return nil, err
	}
	refDir := settings.ReferencesDir
	if err := os.MkdirAll(refDir, 0755); err != nil {
		return nil, fmt.Errorf("failed to create reference directory: %w", err)
	}

	reportPath := filepath.Join(refDir, "orphaned-devices.txt")
	if err := s.saveOrphanReport(orphaned, len(devices), reportPath); err != nil {
		return nil, err
	}

	return &OrphanResult{
		TotalDevices:    len(devices),
		OrphanedDevices: orphaned,
		ReportPath:      reportPath,
	}, nil
}

func (s *Syncer) saveOrphanReport(orphaned []OrphanedDevice, totalDevices int, path string) error {
	var buffer bytes.Buffer
	writer := bufio.NewWriter(&buffer)
	fmt.Fprintf(writer, "# Orphaned Devices Report\n")
	fmt.Fprintf(writer, "# Generated: %s\n", time.Now().Format(time.RFC3339))
	fmt.Fprintf(writer, "# Total devices: %d\n", totalDevices)
	fmt.Fprintf(writer, "# Orphaned (no entities): %d\n", len(orphaned))
	fmt.Fprintln(writer)

	emptyNameCount := 0
	for _, o := range orphaned {
		if o.HasEmptyName {
			emptyNameCount++
		}
	}

	if emptyNameCount > 0 {
		fmt.Fprintf(writer, "## Devices with empty names (%d) - likely stale registry entries:\n\n", emptyNameCount)
		for _, o := range orphaned {
			if o.HasEmptyName {
				info := formatDeviceInfo(o.Device)
				fmt.Fprintf(writer, "%s: (no name) %s\n", o.Device.ID, info)
			}
		}
		fmt.Fprintln(writer)
	}

	namedCount := len(orphaned) - emptyNameCount
	if namedCount > 0 {
		fmt.Fprintf(writer, "## Named devices with no entities (%d) - investigate before deleting:\n\n", namedCount)
		for _, o := range orphaned {
			if !o.HasEmptyName {
				info := formatDeviceInfo(o.Device)
				fmt.Fprintf(writer, "%s: %s %s\n", o.Device.ID, o.Device.Name, info)
			}
		}
	}

	if err := writer.Flush(); err != nil {
		return fmt.Errorf("failed to write orphan report: %w", err)
	}
	if err := util.WriteFileAtomic(path, buffer.Bytes(), 0644); err != nil {
		return fmt.Errorf("failed to publish orphan report: %w", err)
	}

	if !s.quiet {
		color.Green("  Saved orphan report to: %s", path)
	}
	return nil
}

func formatDeviceInfo(d Device) string {
	var parts []string
	if d.Manufacturer != "" || d.Model != "" {
		parts = append(parts, fmt.Sprintf("(%s %s)", d.Manufacturer, d.Model))
	}
	if len(d.ConfigEntries) > 0 {
		parts = append(parts, fmt.Sprintf("[integrations: %s]", strings.Join(d.ConfigEntries, ", ")))
	}
	if d.AreaID != "" {
		parts = append(parts, fmt.Sprintf("area: %s", d.AreaID))
	}
	if d.DisabledBy != "" {
		parts = append(parts, fmt.Sprintf("disabled: %s", d.DisabledBy))
	}
	return strings.Join(parts, " ")
}
